#!/usr/bin/env python3
"""Lists every English text of the game files in FILES as data/files/source.tsv.

Usage: extract.py <folder with the extracted English archives> [repository]
The folder holds the archive contents as the game sees them (missions/,
missions_addon/, maps/, scripts/), extracted from p2arch0_eng.cpr and p2arch1_eng.cpr.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(__file__))
import codec  # noqa: E402
import gmf  # noqa: E402
import p2m  # noqa: E402
from files import FILES  # noqa: E402


def find(root, relative):
    """Case-insensitive lookup of a path below root."""
    path = root
    for part in relative.split("/"):
        names = {name.lower(): name for name in os.listdir(path)}
        if part not in names:
            return None
        path = os.path.join(path, names[part])
    return path


def walk(root, extension):
    for folder, _, names in sorted(os.walk(root)):
        for name in sorted(names):
            if name.lower().endswith(extension):
                yield os.path.join(folder, name)


def lines(path):
    text = open(path, "rb").read().decode("cp1252")
    return [line for line in re.split(r"\r?\n", text) if line]


def main():
    root = sys.argv[1]
    repo = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(__file__), "..", "..")
    rows = {}
    for pattern, (fmt, keys) in FILES.items():
        texts = rows.setdefault(pattern, [])
        if fmt == "mission":
            for path in walk(root, ".p2m"):
                texts += [codec.encode(s) for s in p2m.strings(open(path, "rb").read()) if s]
        elif fmt == "map":
            for path in walk(root, ".gmf"):
                texts += [n.decode("cp1252") for n in gmf.town_names(open(path, "rb").read()) if n]
        else:
            path = find(root, pattern)
            if path is None:
                sys.exit(f"missing {pattern}")
            for line in lines(path):
                if fmt == "ini":
                    key, _, value = line.partition("=")
                    if keys.fullmatch(key.strip()) and re.search(r"[A-Za-z]", value):
                        texts.append(value)
                else:
                    texts.append(line)
    with open(os.path.join(repo, "data", "files", "source.tsv"), "w", encoding="utf-8", newline="\n") as out:
        out.write("# Every English text of the files in FILES (src/files/mod.rs): scope<TAB>English.\n")
        out.write("# Generated by tools/textkit/extract.py; do not edit.\n")
        for pattern, texts in rows.items():
            seen = set()
            for text in texts:
                if text not in seen:
                    seen.add(text)
                    out.write(f"{pattern}\t{text}\n")
            print(f"{pattern}: {len(seen)}")


if __name__ == "__main__":
    main()
